'use strict';
const assert = require('node:assert/strict');
const {catalogTitle, catalogDuration, buildCatalogItems, filterCatalogItems} = require('../warehouse/static/catalog.js');
const videos = [{id:'a',filename:'factory_line-01.mp4',collection:'Factory',group:'Line 1',duration:65},{id:'b',filename:'construction_site.mp4',collection:'Construction',group:'Site B'}];
const snapshot = {recordings:[{id:'r1',library_id:'a',status:'ready'},{id:'demo',filename:'sample.mp4',status:'ready',demo:true}],tracks:[{id:'t1',recording_id:'r1'},{id:'t2',recording_id:'demo'}],analyses:[{track_key:'t1',status:'complete',clip_id:'c1',reviewed:false,report:{review_priority:'review'}},{track_key:'t2',status:'complete',reviewed:true,report:{review_priority:'review'}}],clips:[],jobs:[]};
let items = buildCatalogItems(videos, snapshot);
assert.equal(items.length, 3, 'synthetic demo remains browsable beside VM library');
assert.equal(items[0].status, 'pending');
assert.equal(items[0].flagCount, 1);
assert.equal(items[0].workerCount, 1, 'worker counts stay within a recording');
assert.equal(items[0].trackKey, 't1');
assert.equal(items[0].clipId, 'c1');
assert.deepEqual(filterCatalogItems(items, {status:'needs-review'}).map(item=>item.libraryId), ['a']);
assert.deepEqual(filterCatalogItems(items, {status:'reviewed'}).map(item=>item.recordingId), ['demo']);
assert.deepEqual(filterCatalogItems(items, {status:'not-analysed'}).map(item=>item.libraryId), ['b']);
assert.equal(filterCatalogItems(items, {collection:'Construction',search:'site b'}).length, 1);
assert.equal(filterCatalogItems(items, {search:'FACTORY_line'}).length, 1);
assert.equal(filterCatalogItems(items, {collection:'Construction',search:'factory'}).length, 0);
assert.equal(catalogTitle('forklift_work-01.mp4'), 'forklift work 01');
assert.equal(catalogDuration(65), '1:05');
assert.equal(catalogDuration(null), '');
items = buildCatalogItems(videos, {...snapshot, jobs:[{label:'Dataset · construction_site.mp4',status:'running',progress:30}]});
assert.equal(items.find(item=>item.libraryId==='b').status, 'processing');
items = buildCatalogItems(videos, {...snapshot, jobs:[{label:'Dataset · construction_site.mp4',status:'failed'}]});
assert.equal(items.find(item=>item.libraryId==='b').status, 'failed');
assert.equal(items.find(item=>item.libraryId==='b').workerCount, 0);
items = buildCatalogItems(videos, {...snapshot, recordings:[...snapshot.recordings,{id:'r2',library_id:'b',status:'no_usable_tracks'}]});
assert.equal(items.find(item=>item.libraryId==='b').status, 'analysed');
assert.equal(items.find(item=>item.libraryId==='b').noTracks, true);
assert.equal(items.find(item=>item.libraryId==='b').trackKey, null);
items = buildCatalogItems([{...videos[1],id:'copy-1'},{...videos[1],id:'copy-2'}], {jobs:[{label:'Dataset · construction_site.mp4',status:'running'}]});
assert.ok(items.every(item=>item.status==='unanalysed'), 'ambiguous filenames do not invent a processing identity');
console.log('Catalog status, recording scope, filters and search passed.');
